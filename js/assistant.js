/* CaseMind — MORGAN analytical assistant (simulated by default) */
(function () {
  "use strict";

  const UI = () => window.CaseMind.UI;
  const Storage = () => window.CaseMind.Storage;
  const Cases = () => window.CaseMind.Cases;

  const LABEL = {
    simulated: "SIMULATED",
    live: "LIVE AI",
    fallback: "SIM FALLBACK"
  };

  const state = {
    open: false,
    caseId: null,
    history: [],
    busy: false,
    lastError: ""
  };

  let els = null;

  function cacheEls() {
    if (els) return els;
    els = {
      drawer: document.getElementById("morgan-drawer"),
      scrim: document.getElementById("morgan-scrim"),
      messages: document.getElementById("morgan-messages"),
      context: document.getElementById("morgan-context"),
      chips: document.getElementById("morgan-chips"),
      form: document.getElementById("morgan-form"),
      input: document.getElementById("morgan-input"),
      send: document.getElementById("morgan-send"),
      clear: document.getElementById("morgan-clear"),
      close: document.getElementById("morgan-close"),
      mode: document.getElementById("morgan-mode"),
      subtitle: document.getElementById("morgan-subtitle"),
      footer: document.getElementById("morgan-footer"),
      topBadge: document.getElementById("top-morgan-badge"),
      miniStatus: document.getElementById("morgan-mini-status"),
      miniCopy: document.getElementById("morgan-mini-copy")
    };
    return els;
  }

  function settings() {
    return Storage().getSettings();
  }

  function isLive() {
    return settings().assistantMode === "live";
  }

  function currentCase() {
    return state.caseId ? Cases().byId(state.caseId) : null;
  }

  function currentProgress() {
    return state.caseId ? Storage().getCase(state.caseId) : null;
  }

  function escape(value) {
    return UI().escapeHtml(value);
  }

  function caseTokens(c) {
    const names = [c.title, c.location, c.victim && c.victim.name]
      .concat((c.suspects || []).map((s) => s.name))
      .concat((c.witnesses || []).map((w) => w.name));
    return names.filter(Boolean).join(" · ");
  }

  /* ---------- rendering ---------- */

  function syncModeLabels() {
    const e = cacheEls();
    const live = isLive();
    const label = live ? LABEL.live : LABEL.simulated;
    if (e.mode) {
      e.mode.textContent = label;
      e.mode.classList.toggle("live", live);
    }
    if (e.topBadge) {
      e.topBadge.textContent = live ? "LIVE" : "SIM";
      e.topBadge.title = live ? "Live AI mode enabled" : "Simulated assistant";
    }
    if (e.miniStatus) e.miniStatus.textContent = live ? "Live AI · experimental" : "Analytical assistant";
    if (e.subtitle) e.subtitle.textContent = live ? "Live AI analysis · no solution disclosure" : "Analytical case assistant · rule-based";
    if (e.footer) {
      e.footer.innerHTML = live
        ? `${UI().icon("shield")}<span><strong>Live AI mode.</strong> Responses are generated by an external endpoint and may be inaccurate. Case facts only; the solution is never sent.</span>`
        : `${UI().icon("shield")}<span><strong>Simulated assistant.</strong> Rule-based analysis only. Never invents evidence and never reveals the solution.</span>`;
    }
  }

  function renderContext() {
    const e = cacheEls();
    if (!e.context) return;
    const c = currentCase();
    if (!c) {
      e.context.innerHTML = `<i></i><span>No active case · <strong>Open a case file to begin</strong></span>`;
      return;
    }
    const p = currentProgress();
    const total = (p && p.evidenceSeen ? p.evidenceSeen.length : 0);
    e.context.innerHTML = `<i></i><span>CASE ${escape(c.number)} · <strong>${escape(c.title)}</strong> · ${total}/${c.evidence.length} evidence logged</span>`;
  }

  function renderMessage(message) {
    const role = message.role === "user" ? "user" : "assistant";
    const meta = role === "user"
      ? "You"
      : `MORGAN${message.mode === "live" ? " · LIVE" : message.mode === "fallback" ? " · SIM FALLBACK" : " · SIM"}`;
    const content = escape(message.content || "")
      .split("\n")
      .map((line) => {
        if (/^\s*[•·-]\s+/.test(line)) {
          return `<span class="morgan-bullet">${line.replace(/^\s*[•·-]\s+/, "")}</span>`;
        }
        return line;
      })
      .join("\n");
    return `<div class="morgan-msg ${role}">
      <div class="morgan-msg-meta">${escape(meta)}</div>
      <div class="morgan-bubble">${content}</div>
    </div>`;
  }

  function introHtml() {
    const c = currentCase();
    if (!c) {
      return `<div class="morgan-intro">
        <div class="morgan-intro-label">${UI().icon("spark")} Assistant briefing</div>
        <p>I am MORGAN, the analytical assistant built into CaseMind. Open a case file and I can review evidence, test alibis, and point you toward unexplored leads. I work from the case record — I will never invent facts or state the solution.</p>
      </div>`;
    }
    const live = isLive();
    return `<div class="morgan-intro">
      <div class="morgan-intro-label">${UI().icon("spark")} ${live ? "Live session" : "Simulated session"}</div>
      <p>${live
        ? "Live AI mode is active. I can discuss the case record, but I will not identify the culprit or reveal the solution. If the endpoint fails, I fall back to rule-based analysis."
        : "I work from a fixed rule set built around this case file. I can point to evidence, challenge alibis, and track contradictions — but every answer is simulation, not a separate intelligence."}</p>
    </div>`;
  }

  function renderMessages() {
    const e = cacheEls();
    if (!e.messages) return;
    e.messages.innerHTML = introHtml() + state.history.map(renderMessage).join("");
    if (state.busy) {
      e.messages.insertAdjacentHTML("beforeend", `<div class="morgan-msg assistant">
        <div class="morgan-msg-meta">MORGAN · THINKING</div>
        <div class="morgan-bubble"><span class="morgan-typing"><i></i><i></i><i></i></span></div>
      </div>`);
    }
    e.messages.scrollTop = e.messages.scrollHeight;
  }

  function renderChips() {
    const e = cacheEls();
    if (!e.chips) return;
    const c = currentCase();
    const chips = c
      ? ["Give me a hint", "Review contradictions", "What next?", "Check the alibis", "Summarise the case"]
      : ["How does MORGAN work?", "Open a case"];
    e.chips.innerHTML = chips
      .map((label) => `<button class="morgan-chip" type="button" data-morgan-chip="${escape(label)}">${escape(label)}</button>`)
      .join("");
  }

  function renderAll() {
    syncModeLabels();
    renderContext();
    renderMessages();
    renderChips();
    updateSidebarCopy();
  }

  function updateSidebarCopy() {
    const e = cacheEls();
    const c = currentCase();
    if (e.miniCopy) {
      if (!c) e.miniCopy.textContent = "Evidence cross-referencing and case analysis.";
      else e.miniCopy.textContent = `${c.title} — ${isLive() ? "live AI mode" : "simulated analysis"}.`;
    }
    if (e.miniStatus) e.miniStatus.textContent = isLive() ? "Live AI · experimental" : "Analytical assistant";
  }

  function persist() {
    if (!state.caseId) return;
    Storage().setMorganHistory(state.caseId, state.history);
  }

  /* ---------- drawer ---------- */

  function open(caseId, options) {
    const opts = options || {};
    if (caseId && caseId !== state.caseId) setCase(caseId);
    else if (!caseId) {
      const active = Storage().getActiveCase();
      if (active) setCase(active.caseId);
    }
    const e = cacheEls();
    state.open = true;
    e.drawer.classList.add("open");
    e.drawer.setAttribute("aria-hidden", "false");
    e.scrim.classList.add("open");
    renderAll();
    if (opts.focus !== false) {
      setTimeout(() => { try { e.input.focus({ preventScroll: true }); } catch (err) { /* ignore */ } }, 260);
    }
  }

  function close() {
    const e = cacheEls();
    state.open = false;
    e.drawer.classList.remove("open");
    e.drawer.setAttribute("aria-hidden", "true");
    e.scrim.classList.remove("open");
  }

  function toggle(caseId) {
    if (state.open) close();
    else open(caseId);
  }

  function setCase(caseId) {
    if (!caseId) {
      state.caseId = null;
      state.history = [];
      renderAll();
      return;
    }
    if (state.caseId === caseId) {
      renderAll();
      return;
    }
    state.caseId = caseId;
    const progress = Storage().getCase(caseId);
    state.history = progress && Array.isArray(progress.morganHistory) ? progress.morganHistory.slice() : [];
    state.lastError = "";
    renderAll();
  }

  function clear() {
    state.history = [];
    if (state.caseId) Storage().setMorganHistory(state.caseId, []);
    renderAll();
    UI().toast("MORGAN conversation cleared.", "info");
  }

  /* ---------- analysis helpers ---------- */

  function findSuspectByName(c, text) {
    const lower = String(text || "").toLowerCase();
    return (c.suspects || []).find((s) => {
      const name = s.name.toLowerCase();
      if (lower.includes(name)) return true;
      const surname = name.split(/\s+/).pop();
      return surname && surname.length > 3 && lower.includes(surname);
    }) || null;
  }

  function findEvidenceByName(c, text) {
    const lower = String(text || "").toLowerCase();
    return (c.evidence || []).find((ev) => {
      const name = ev.name.toLowerCase();
      return lower.includes(name) || (ev.id && lower.includes(ev.id.toLowerCase()));
    }) || null;
  }

  function suspectCoverage(c, p, suspect) {
    const asked = (p && p.questionsAsked) || [];
    const done = (suspect.questions || []).filter((q) => asked.includes(`${suspect.id}:${q.id}`)).length;
    return `${done}/${(suspect.questions || []).length}`;
  }

  function hintReply(c, p) {
    const hints = c.hints || [];
    if (!hints.length) return "This case file has no prepared hints. Return to the evidence and timeline; the contradiction is usually in the timing.";
    const used = (p && p.hintsUsed) || 0;
    if (used >= hints.length) {
      return `You have used all ${hints.length} prepared hints for this case. I will not invent a new one.\n\n• Re-read every suspect statement against the timeline.\n• Check which alibi has no independent witness.\n• Count which physical evidence has no innocent explanation.`;
    }
    Storage().addHint(state.caseId);
    return `Field note ${used + 1} of ${hints.length} — hint penalty now ${Math.min(15, (used + 1) * 5)} points.\n\n${hints[used]}\n\nUse "Review contradictions" when you have logged the matching evidence.`;
  }

  function contradictionReply(c, p) {
    const found = (p && p.contradictionsFound) || [];
    if (!found.length) {
      return `No contradictions are documented in your case file yet.\n\n• Open every piece of physical or digital evidence.\n• Question each suspect about their own alibi.\n• Use Analysis → Compare to test one suspect against one exhibit.\n\nI will not tell you which alibi breaks — that is the work.`;
    }
    const items = (c.contradictions || []).filter((x) => found.includes(x.id));
    return `You have surfaced ${items.length} of ${(c.contradictions || []).length} documented contradictions.\n\n` +
      items.map((x) => `• ${x.title}${x.hint ? ` — ${x.hint}` : ""}`).join("\n");
  }

  function nextStepReply(c, p) {
    const unseen = (c.evidence || []).filter((ev) => !(p && p.evidenceSeen || []).includes(ev.id));
    const unread = (c.witnesses || []).filter((w) => !(p && p.witnessesRead || []).includes(w.id));
    const unasked = [];
    (c.suspects || []).forEach((s) => {
      s.questions.forEach((q) => {
        if (!(p && p.questionsAsked || []).includes(`${s.id}:${q.id}`)) unasked.push(`${s.name} — "${q.text}"`);
      });
    });
    const found = (p && p.contradictionsFound) || [];
    const lines = [];
    if (unseen.length) lines.push(`• ${unseen.length} exhibit${unseen.length === 1 ? "" : "s"} still unlogged. Start with "${unseen[0].name}".`);
    if (unread.length) lines.push(`• ${unread.length} witness statement${unread.length === 1 ? "" : "s"} unread. ${unread[0].name} is waiting.`);
    if (unasked.length) lines.push(`• ${unasked.length} question${unasked.length === 1 ? "" : "s"} not yet asked. Try: ${unasked[0]}.`);
    if ((c.contradictions || []).length > found.length) lines.push(`• ${(c.contradictions || []).length - found.length} contradiction${(c.contradictions || []).length - found.length === 1 ? "" : "s"} remain unrecorded. Compare alibis with exact timestamps.`);
    if (!lines.length) lines.push("• Your case file is comprehensive. Test the strongest alibi once more, then prepare the final accusation.");
    return `Priority check:\n\n${lines.join("\n")}`;
  }

  function evidenceReply(c, p) {
    const seen = (p && p.evidenceSeen) || [];
    if (!seen.length) return `No exhibits are logged yet. Open Evidence and examine the first item. I can only discuss what is in your case file.\n\nThere are ${c.evidence.length} exhibits to review.`;
    const items = c.evidence.filter((ev) => seen.includes(ev.id));
    return `Logged exhibits (${items.length}/${c.evidence.length}):\n\n` +
      items.map((ev) => `• ${ev.name} — ${ev.summary}`).join("\n") +
      (seen.length < c.evidence.length ? `\n\n${c.evidence.length - seen.length} exhibits remain unread.` : "\n\nEvery exhibit is logged.");
  }

  function alibiReply(c, p) {
    const lines = (c.suspects || []).map((s) => {
      const contradictions = (c.contradictions || []).filter((x) => x.suspectId === s.id && (p && p.contradictionsFound || []).includes(x.id));
      return `• ${s.name} — ${s.alibi} (questions asked: ${suspectCoverage(c, p, s)}${contradictions.length ? `, contradictions recorded: ${contradictions.length}` : ""})`;
    });
    return `Declared alibis on file:\n\n${lines.join("\n")}\n\nAn alibi is only as strong as its independent witness. Compare each claim with the timeline.`;
  }

  function summaryReply(c, p) {
    const seen = (p && p.evidenceSeen || []).length;
    const asked = (p && p.questionsAsked || []).length;
    const totalQ = (c.suspects || []).reduce((n, s) => n + s.questions.length, 0);
    const found = (p && p.contradictionsFound || []).length;
    return `${c.title} — ${c.difficultyLabel}, case ${c.number}.\n\n• ${c.location}, ${c.date}, window ${c.timeWindow}.\n• Evidence logged: ${seen}/${c.evidence.length}.\n• Questions asked: ${asked}/${totalQ}.\n• Witnesses read: ${(p && p.witnessesRead || []).length}/${c.witnesses.length}.\n• Contradictions surfaced: ${found}/${c.contradictions.length}.\n• Hints used: ${(p && p.hintsUsed) || 0}.\n\nA final accusation requires a culprit, motive, method, and up to three exhibits. I will not name the culprit.`;
  }

  function suspectReply(c, p, suspect) {
    const found = (c.contradictions || []).filter((x) => x.suspectId === suspect.id && (p && p.contradictionsFound || []).includes(x.id));
    return `${suspect.name} — ${suspect.role}.\n\n• Declared alibi: ${suspect.alibi}\n• Background: ${suspect.background}\n• Interviews completed: ${suspectCoverage(c, p, suspect)}\n• Contradictions recorded: ${found.length ? found.map((x) => x.title).join("; ") : "none yet"}\n\nI can discuss what is on record. I will not speculate on guilt.`;
  }

  function evidenceItemReply(c, p, evidence) {
    const seen = p && (p.evidenceSeen || []).includes(evidence.id);
    if (!seen) return `"${evidence.name}" is not logged in your case file yet. Open it under Evidence before we discuss it.`;
    return `${evidence.name} (${evidence.category})\n\n• Location: ${evidence.location}\n• Finding: ${evidence.description}\n• Analysis: ${evidence.analysis}`;
  }

  function simulateSimulated(text) {
    const c = currentCase();
    const p = currentProgress();
    const lower = String(text || "").toLowerCase();

    if (!c) {
      if (/open a case|start|begin|case file/.test(lower)) {
        return "Use Case Files in the sidebar. The first case is available immediately — no registration or briefing call required.";
      }
      if (/live|real ai|api/.test(lower)) {
        return "CaseMind runs a simulated assistant by default. Settings → MORGAN assistant lets you switch to a live OpenAI-compatible endpoint. The endpoint is optional and never mandatory.";
      }
      return "I need an active case before I can analyse evidence. Open Case Files, choose a brief, and begin an investigation. I will meet you here.";
    }

    if (/(hint|stuck|help me|nudge|clue)/.test(lower)) return hintReply(c, p);
    if (/(contradiction|inconsisten|lie|lying|alibi break)/.test(lower)) return contradictionReply(c, p);
    if (/(what next|next step|what should|where do i|priority|todo|to do)/.test(lower)) return nextStepReply(c, p);
    if (/(alibi|where was|where were|timeline of suspect)/.test(lower)) return alibiReply(c, p);
    if (/(summar|overview|status|progress|case file)/.test(lower)) return summaryReply(c, p);
    if (/(evidence|exhibit|forensic|proof)/.test(lower)) {
      const named = findEvidenceByName(c, text);
      if (named) return evidenceItemReply(c, p, named);
      return evidenceReply(c, p);
    }
    if (/(guilty|culprit|murderer|thief|who did|who stole|solution|answer)/.test(lower)) {
      return "I will not name a culprit or reveal the solution. That would remove the investigation.\n\nI can help you test the chain instead:\n• Which suspect had access at the exact time?\n• Which alibi lacks an independent witness?\n• Which exhibit contradicts a statement you have already recorded?\n\nWhen those three answers agree, make the accusation yourself.";
    }
    const suspect = findSuspectByName(c, text);
    if (suspect) return suspectReply(c, p, suspect);
    const evidence = findEvidenceByName(c, text);
    if (evidence) return evidenceItemReply(c, p, evidence);
    if (/(hello|hi|hey|morgan)/.test(lower) && lower.length < 24) {
      return `MORGAN online. Case ${c.number}: ${c.title}.\n\nAsk me about a suspect by name, a specific exhibit, the timeline, or say "Give me a hint". I will not state the solution.`;
    }
    return `I can analyse the case record, not invent outside facts.\n\nTry:\n• "Give me a hint"\n• "Review contradictions"\n• "What next?"\n• "Check the alibis"\n• Ask about a suspect by name\n• Ask about a logged exhibit by name\n\nCurrent case: ${c.title}.`;
  }

  function liveSystemPrompt(c, p) {
    const seenEvidence = (p && p.evidenceSeen || []).map((id) => (c.evidence || []).find((ev) => ev.id === id)).filter(Boolean);
    const asked = (p && p.questionsAsked) || [];
    const found = (p && p.contradictionsFound || []).map((id) => (c.contradictions || []).find((x) => x.id === id)).filter(Boolean);
    return [
      "You are MORGAN, the analytical assistant inside a fictional detective training application.",
      "You must NEVER identify, name, hint at, or speculate about which suspect is guilty. Never reveal or reconstruct the solution. There is no solution field in your context.",
      "Do not invent evidence, witnesses, timestamps, or forensic results. Only use the case record provided.",
      "Answer as a terse, professional investigator in at most 150 words. Use short bullet points when listing. Point the player toward investigative work rather than doing the deduction for them.",
      `CASE RECORD: ${JSON.stringify({
        title: c.title,
        location: c.location,
        date: c.date,
        timeWindow: c.timeWindow,
        scene: c.scene && c.scene.summary,
        suspects: (c.suspects || []).map((s) => ({ name: s.name, role: s.role, alibi: s.alibi, profile: s.summary })),
        witnesses: (c.witnesses || []).map((w) => ({ name: w.name, role: w.role, summary: w.summary })),
        loggedEvidence: seenEvidence.map((ev) => ({ name: ev.name, category: ev.category, summary: ev.summary, analysis: ev.analysis })),
        questionsAsked: asked,
        contradictionsSurfaced: found.map((x) => ({ title: x.title, detail: x.detail }))
      })}`
    ].join("\n");
  }

  /* ---------- conversation ---------- */

  function sleep(ms) {
    return new Promise((resolve) => setTimeout(resolve, ms));
  }

  function push(role, content, mode) {
    state.history.push({ role, content, mode: mode || "sim", at: new Date().toISOString() });
    if (state.history.length > 60) state.history = state.history.slice(-60);
    persist();
  }

  async function send(text) {
    const clean = String(text || "").trim();
    if (!clean || state.busy) return;
    const e = cacheEls();
    state.busy = true;
    e.send.disabled = true;
    push("user", clean, "user");
    renderMessages();
    e.messages.scrollTop = e.messages.scrollHeight;

    const c = currentCase();
    const p = currentProgress();
    const hintIntent = c && /(hint|stuck|nudge|clue)/i.test(clean);
    const live = isLive() && c && !hintIntent;

    try {
      await sleep(live ? 260 : 520);
      if (live) {
        const s = settings();
        const messages = [
          { role: "system", content: liveSystemPrompt(c, p) },
          ...state.history.filter((m) => m.role === "user" || m.role === "assistant").slice(-8).map((m) => ({ role: m.role, content: m.content })),
          { role: "user", content: clean }
        ];
        try {
          const reply = await window.CaseMind.API.chat({
            endpoint: s.liveEndpoint,
            key: Storage().getLiveKey(),
            model: s.liveModel,
            messages
          });
          push("assistant", reply, "live");
        } catch (err) {
          const fallback = simulateSimulated(clean);
          const reason = err && err.message ? err.message : "Live endpoint unavailable";
          const hint = /402|429|limit|rate/i.test(reason)
            ? "The free endpoint is rate-limited right now (one reply per 45 seconds per IP)."
            : /401|403|key/i.test(reason)
              ? "Check the API key and endpoint in Settings."
              : "The endpoint did not answer in time.";
          push("assistant", `Live endpoint unavailable — ${hint}\nFalling back to the built-in rule set.\n\n${fallback}`, "fallback");
          state.lastError = reason;
        }
      } else {
        const reply = simulateSimulated(clean);
        push("assistant", reply, "sim");
      }
    } finally {
      state.busy = false;
      e.send.disabled = false;
      renderMessages();
      e.messages.scrollTop = e.messages.scrollHeight;
      UI().checkAchievementsSoon && UI().checkAchievementsSoon();
    }
  }

  function submit(event) {
    event.preventDefault();
    const e = cacheEls();
    const value = e.input.value;
    e.input.value = "";
    e.input.style.height = "auto";
    send(value);
  }

  function handleChip(event) {
    const btn = event.target.closest("[data-morgan-chip]");
    if (!btn) return;
    const label = btn.getAttribute("data-morgan-chip");
    if (label === "Open a case") {
      close();
      if (window.CaseMind.App && window.CaseMind.App.navigate) window.CaseMind.App.navigate("#/cases");
      return;
    }
    send(label);
  }

  function autoGrow() {
    const e = cacheEls();
    e.input.style.height = "auto";
    e.input.style.height = `${Math.min(100, e.input.scrollHeight)}px`;
  }

  function init() {
    const e = cacheEls();
    if (!e.drawer) return;

    document.getElementById("top-morgan").addEventListener("click", () => toggle());
    document.getElementById("btn-morgan-sidebar").addEventListener("click", () => open());
    if (e.close) e.close.addEventListener("click", close);
    if (e.scrim) e.scrim.addEventListener("click", close);
    if (e.clear) e.clear.addEventListener("click", clear);
    if (e.form) e.form.addEventListener("submit", submit);
    if (e.chips) e.chips.addEventListener("click", handleChip);
    if (e.input) {
      e.input.addEventListener("input", autoGrow);
      e.input.addEventListener("keydown", (event) => {
        if (event.key === "Enter" && !event.shiftKey) {
          event.preventDefault();
          e.form.requestSubmit();
        }
      });
    }
    renderAll();
  }

  function refreshCase() {
    if (state.caseId && !Cases().byId(state.caseId)) {
      state.caseId = null;
      state.history = [];
    }
    renderAll();
  }

  window.CaseMind = window.CaseMind || {};
  window.CaseMind.Assistant = {
    init,
    open,
    close,
    toggle,
    setCase,
    refreshCase,
    clear,
    send,
    isLive,
    syncModeLabels
  };
})();
